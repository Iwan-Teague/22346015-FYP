/// SHA-256 of `bytes`: the ONE digest function the harness uses (design
/// §1.4). Built on the single SHA-256 crate on the purity allowlist
/// (`sha2`, RustCrypto, pure Rust, default features off).
pub fn sha256(bytes: &[u8]) -> Digest {
    sha256_parts(&[bytes])
}

/// SHA-256 over the concatenation of `parts`, without copying them into one
/// buffer (used for the journal's `sha256(prev || canonical line)`).
pub fn sha256_parts(parts: &[&[u8]]) -> Digest {
    use sha2::Digest as _;
    let mut h = sha2::Sha256::new();
    for p in parts {
        h.update(p);
    }
    let out: [u8; 32] = h.finalize().into();
    Digest::from_bytes(out)
}

/// Incremental SHA-256 over bytes fed in pieces (H1e-2a confirming review
/// NF-1: a large file is hashed chunk by chunk, never read whole). The same
/// digest as [`sha256`] over the concatenation. Pure: the caller does the
/// reading.
#[derive(Clone, Default)]
pub struct Sha256Stream(sha2::Sha256);

impl fmt::Debug for Sha256Stream {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str("Sha256Stream")
    }
}

impl Sha256Stream {
    /// A fresh hash.
    pub fn new() -> Self {
        Self::default()
    }

    /// Feed more bytes.
    pub fn update(&mut self, bytes: &[u8]) {
        use sha2::Digest as _;
        self.0.update(bytes);
    }

    /// The digest of everything fed.
    pub fn finish(self) -> Digest {
        use sha2::Digest as _;
        let out: [u8; 32] = self.0.finalize().into();
        Digest::from_bytes(out)
    }
}

/// A run identity (design §2.8): 128 bits, time-ordered then random,
/// written as exactly 32 lowercase hex characters. Its own strict type
/// (H1c confirming review NF-3): a run id becomes a directory name under
/// `state_root/runs/`, so it can never be `.`, `..`, contain a separator or
/// start with `.` or `-`; the grammar makes all of those impossible.
///
/// Pure: the caller supplies the time and the randomness.
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub struct RunId(String);

impl RunId {
    /// Build from a Unix-millisecond timestamp (the high 48 bits, so ids
    /// sort by creation time) and 80 random bits.
    pub fn new(unix_ms: u64, random: [u8; 10]) -> Self {
        let mut s = format!("{:012x}", unix_ms & 0xFFFF_FFFF_FFFF);
        for b in random {
            s.push_str(&format!("{b:02x}"));
        }
        Self(s)
    }

    /// Parse an existing id: exactly 32 lowercase hex characters.
    pub fn parse(s: &str) -> Option<Self> {
        let ok = s.len() == 32 && s.bytes().all(|b| matches!(b, b'0'..=b'9' | b'a'..=b'f'));
        ok.then(|| Self(s.to_owned()))
    }

    /// The id.
    pub fn as_str(&self) -> &str {
        &self.0
    }
}

impl fmt::Display for RunId {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&self.0)
    }
}

/// A per-turn random nonce for the untrusted-block delimiters (design
/// §2.3): 16..=64 lowercase hex characters, generated by the run driver
/// from OS randomness. (Re-exported by the model layer as `RenderNonce`.)
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Nonce(String);

impl Nonce {
    /// Validate a nonce.
    pub fn new(hex: &str) -> Option<Self> {
        let ok = (16..=64).contains(&hex.len())
            && hex.bytes().all(|b| matches!(b, b'0'..=b'9' | b'a'..=b'f'));
        ok.then(|| Self(hex.to_owned()))
    }

    /// The nonce.
    pub fn as_str(&self) -> &str {
        &self.0
    }
}

